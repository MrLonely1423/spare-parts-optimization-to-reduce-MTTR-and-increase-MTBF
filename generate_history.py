"""Generate SYNTHETIC maintenance history that mimics DX / work-order style data."""
import numpy as np
import pandas as pd
from sim_core import COMPONENTS, BASELINE, START, DAYS, HPD, simulate

SEED = 2024
events, cens = simulate(BASELINE, seed=SEED)
rng = np.random.default_rng(SEED + 1)

events = events.sort_values("time_d").reset_index(drop=True)
events["unit_id"] = events.apply(
    lambda r: f"L{r.unit % 3 + 1}-{r.component_id}-{int(r.unit) + 1:02d}", axis=1)

# previous replacement date per unit/component, previous breakdown flag
events = events.sort_values(["component_id", "unit", "time_d"]).reset_index(drop=True)
events["prev_time_d"] = events.groupby(["component_id", "unit"])["time_d"].shift(1).fillna(0.0)
events["prev_kind"] = events.groupby(["component_id", "unit"])["kind"].shift(1)
events["repeat_flag"] = ((events.kind == "BD") & (events.prev_kind == "BD")
                         & ((events.time_d - events.prev_time_d) <= 30)).astype(int)
events = events.sort_values("time_d").reset_index(drop=True)

wo = []
for i, r in events.iterrows():
    c = COMPONENTS[r.component_id]
    start = START + pd.Timedelta(days=int(r.time_d)) + pd.Timedelta(
        hours=6 + (r.time_d % 1) * 16)
    total = r.repair_min + r.wait_min
    end = start + pd.Timedelta(minutes=total)
    if r.kind == "BD":
        desc, cause = c["issues"][rng.integers(len(c["issues"]))]
    else:
        desc, cause = "Scheduled replacement (PM)", "Planned replacement"
    wo.append(dict(
        wo_id=f"SYN-WO-{i + 1:05d}",
        event_date=start.date(),
        repair_start=start.round("min"),
        repair_end=end.round("min"),
        line=f"L{r.unit % 3 + 1}",
        unit_id=r.unit_id,
        component_id=r.component_id,
        component=c["name"],
        wo_type="Breakdown" if r.kind == "BD" else "PM",
        failure_description=desc,
        cause=cause,
        part_no=c["part_no"],
        qty=1,
        part_installed_date=(START + pd.Timedelta(days=int(r.prev_time_d))).date(),
        run_hours_since_install=round(r.age_h, 1),
        active_repair_min=round(r.repair_min, 1),
        wait_for_part_min=round(r.wait_min, 1),
        total_stop_min=round(total, 1),
        stock_on_hand_before=int(r.stock_before),
        stockout_flag=int(r.stockout),
        repeat_problem=int(r.repeat_flag),
    ))
wo = pd.DataFrame(wo)

assets = pd.DataFrame([
    dict(unit_id=f"L{u % 3 + 1}-{cid}-{u + 1:02d}", line=f"L{u % 3 + 1}", area=c["area"],
         component_id=cid, component=c["name"], first_install_date=START.date())
    for cid, c in COMPONENTS.items() for u in range(c["units"])])

parts = pd.DataFrame([
    dict(part_no=c["part_no"], part_name=c["name"], component_id=cid,
         unit_cost_thb=c["cost"], lead_time_days=c["lead_days"],
         current_reorder_point=BASELINE[cid]["s"], current_order_up_to=BASELINE[cid]["S"],
         critical=("Yes" if c["critical"] else "No"))
    for cid, c in COMPONENTS.items()])

truth = pd.DataFrame([
    dict(component_id=cid, component=c["name"], true_beta=c["beta"], true_eta_run_h=c["eta"],
         existing_pm_interval_h=c["pm_h"])
    for cid, c in COMPONENTS.items()])

readme = pd.DataFrame({"README": [
    "SYNTHETIC DATA - generated by simulation. NOT real Toyota data. Do not present as real results.",
    f"Observation window: {START.date()} for {DAYS} days, {HPD:.0f} run-hours per day.",
    "Failure patterns per component are known to the generator and stored in ground_truth.csv (kept separate).",
    "Purpose: build and test the analysis pipeline before real DX / work order exports arrive.",
    "Assumption: all units were installed new at the start of the window. Real data usually has unknown",
    "  install ages for parts already in service (left truncation); handle this when using real data.",
    "Planned (PM) replacements are right-censored lifetimes: the part had not failed when replaced.",
    "Column names mimic the 'must have / should have' data requirements in the project proposal.",
]})

with pd.ExcelWriter("synthetic_maintenance_history.xlsx", engine="openpyxl") as xw:
    readme.to_excel(xw, "README", index=False)
    wo.to_excel(xw, "work_orders", index=False)
    assets.to_excel(xw, "assets", index=False)
    parts.to_excel(xw, "parts", index=False)
truth.to_csv("ground_truth.csv", index=False)
print(wo.groupby(["component", "wo_type"]).size().unstack(fill_value=0))
print(len(wo), "work orders")
